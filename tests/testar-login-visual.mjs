import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const page=readFileSync("src/app/entrar/page.tsx","utf8");
const form=readFileSync("src/components/formulario-login.tsx","utf8");
const css=readFileSync("src/app/globals.css","utf8");
assert.match(page, /FormularioLogin/);
assert.match(page, /destinoSeguro\(retorno\)/);
assert.match(page, /AlternarTema/);
assert.match(page, /role="alert"/);
assert.match(form, /method="post"/);
assert.match(form, /action="\/api\/autenticacao\/entrar"/);
for (const name of ["usuario","senha","retorno"]) assert.match(form,new RegExp(`name="${name}"`));
assert.match(form, /current-password/);
assert.match(form, /getModifierState\("CapsLock"\)/);
assert.match(form, /setMostrarSenha/);
assert.match(form, /disabled=\{!pronta \|\| enviando\}/);
assert.match(css, /\.login-shell/);
assert.match(css, /\.login-password-wrap/);
assert.match(css, /@media\(max-width:680px\)/);
console.log("Login visual: estrutura, rota de autenticação, interação e responsividade conferidas.");
