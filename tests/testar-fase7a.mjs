import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
const raiz=process.cwd();
const ler=(p)=>readFileSync(join(raiz,p),"utf8");
const rotas=["src/app/artigos/page.tsx","src/app/categorias/page.tsx","src/app/busca/page.tsx","src/app/admin/page.tsx","src/app/entrar/page.tsx"];
for(const rota of rotas)assert.ok(existsSync(join(raiz,rota)),`Rota ausente: ${rota}`);
const shell=ler("src/components/estrutura-aplicacao.tsx");
for(const item of ['href:"/"','href:"/busca"','href:"/artigos"','href:"/categorias"','href:"/admin"','href:"/admin/artigos"','href:"/admin/usuarios"','href:"/admin/auditoria"'])assert.ok(shell.includes(item),`Menu sem destino ${item}`);
assert.ok(shell.includes('papel!=="leitor"'),"Menu administrativo visível para leitor");
assert.ok(shell.includes('papel==="administrador"'),"Permissões administrativas não verificadas");
assert.ok(shell.includes('salvarPreferencia(CHAVE'),"Preferência de recolhimento não persistida");
assert.ok(shell.includes('e.key==="Escape"'),"Falta suporte à tecla Escape");
assert.ok(shell.includes('aria-expanded={mobileAberta}'),"Botão mobile sem estado ARIA");
assert.ok(shell.includes('pathname==="/entrar"'),"Login deve permanecer sem sidebar");
const css=ler("src/app/globals.css");
for(const marca of [".sidebar-app", ".topbar-app", ".hero-inicio", "@media(max-width:1000px)","prefers-reduced-motion"])assert.ok(css.includes(marca),`Estilo ausente: ${marca}`);
const layout=ler("src/app/layout.tsx");
assert.ok(layout.includes("<EstruturaAplicacao"),"Layout global sem shell");
const legado=ler("src/app/admin/layout.tsx");
assert.ok(!legado.includes('href="/admin/usuarios"'),"Navegação duplicada no painel");
assert.ok(!existsSync(join(raiz,"db/003_redesign.sql")),"Redesign não deve exigir migração de banco");
console.log("Fase 7A: estrutura, rotas, permissões do menu e responsividade conferidas.");
