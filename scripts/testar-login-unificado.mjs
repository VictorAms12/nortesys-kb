import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const ler = path => readFileSync(path,"utf8");
const form = ler("src/components/formulario-login.tsx");
assert.match(form, /action="\/api\/autenticacao\/entrar" method="post"/);
assert.match(form, /name="usuario"/);assert.match(form, /name="senha"/);assert.match(form, /name="retorno"/);
assert.doesNotMatch(form, /minLength=\{/);
assert.match(form, /readOnly=\{enviando\}/);
for (const nome of ["usuario","senha"]) {
  const campo = form.split(`name="${nome}"`)[1]?.split("/>")[0] ?? "";
  assert.match(campo, /disabled=\{!pronta\}/);
  assert.doesNotMatch(campo, /disabled=\{!pronta \|\| enviando\}/);
}
const users = ler("src/lib/usuarios.ts");
assert.match(users, /credencial.length === 0/);
assert.doesNotMatch(users, /credencial.length < 12/);
assert.match(users, /FORMATO_USUARIO = \/\^\[a-z\]\[a-z0-9._-\]\{2,39\}\$\//);
const loginThrottle = ler("src/lib/limite-login.ts");
assert.match(loginThrottle, /\{2,39\}/);
const adm = ler("src/lib/admin-usuarios.ts");
assert.match(adm, /credencial.length===0/);assert.match(adm, /credencial.trim\(\).length===0/);
assert.doesNotMatch(adm, /credencial.length<12/);
const adminPage = ler("src/app/admin/usuarios/page.tsx");
assert.equal((adminPage.match(/name="credencial"/g) || []).length, 2);
assert.doesNotMatch(adminPage, /minLength=\{12\}/);
const route = ler("src/app/api/admin/usuarios/route.ts");
assert.equal((route.match(/gerarCredencialHash\(typeof f.get\("credencial"\)/g)||[]).length, 2);
assert.doesNotMatch(route, /gerarCredencialHash\(valor\("credencial"\)\)/);
const css=ler("src/app/globals.css");assert.match(css, /max-height: 690px/);
assert.match(css, /min-height: 100svh;/);
const page=ler("src/app/entrar/page.tsx");assert.match(page,/FormularioLogin/);
console.log("OK: login, criação/redefinição de senhas e layout unificados estruturalmente.");
